//! Drives the command-line error paths that need no network and no OS
//! credential store, with marker strings planted in the inputs, and checks
//! that no marker reaches stdout or stderr. Commands that read the
//! credential store (`check`, `setup`, `clear-local-data` without a refusal)
//! are covered by unit tests instead, so this test never touches a keyring.

use std::io::Write;
use std::process::{Command, Output, Stdio};

const BIN: &str = env!("CARGO_BIN_EXE_librelink-mcp-rs");

// Synthetic markers only.
const NAME: &str = "Synthetic Q. Leakmarker";
const SERIAL: &str = "LEAKMARKER-SERIAL-0042";
const NOTE: &str = "LEAKMARKER-NOTE";
const VALUE: &str = "987.6";
const SECRET: &str = "LEAKMARKER-SECRET";

fn run(args: &[&str], stdin: &str) -> Output {
    let mut child = Command::new(BIN)
        .args(args)
        .env_remove("LIBRELINK_MCP_DEBUG")
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .expect("start the binary");
    child
        .stdin
        .take()
        .unwrap()
        .write_all(stdin.as_bytes())
        .unwrap();
    child.wait_with_output().unwrap()
}

fn assert_clean(label: &str, output: &Output) {
    let text = format!(
        "{}{}",
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    );
    for marker in [NAME, SERIAL, NOTE, VALUE, SECRET, "LEAKMARKER"] {
        assert!(
            !text.contains(marker),
            "{label}: {marker} in output:\n{text}"
        );
    }
}

fn libreview_csv(rows: &[&str]) -> String {
    let mut lines = vec![
        format!("Glucose Data,Generated on,synthetic,Generated by,{NAME}"),
        "Device,Serial Number,Device Timestamp,Record Type,Historic Glucose mg/dL,\
         Scan Glucose mg/dL,Notes"
            .to_owned(),
    ];
    lines.extend(rows.iter().map(|row| row.to_string()));
    lines.join("\r\n")
}

#[test]
fn command_line_errors_never_echo_inputs_or_file_contents() {
    let dir = tempfile::TempDir::new().unwrap();
    let db = dir.path().join("readings.sqlite3");
    let db = db.to_str().unwrap();

    let mut cases: Vec<(&str, Output)> = Vec::new();
    cases.push(("unknown command", run(&[SECRET], "")));
    cases.push(("serve option", run(&["serve", "--bogus", SECRET], "")));
    cases.push((
        "collect option",
        run(&["collect", "--retention-days", SECRET], ""),
    ));
    cases.push((
        "set-api-version",
        run(&["set-api-version"], &format!("{SECRET}\n")),
    ));
    cases.push((
        "select-patient",
        run(&["select-patient"], &format!("{SECRET}\n")),
    ));

    // A database file that is not SQLite, holding a marker.
    let not_sqlite = dir.path().join("broken.sqlite3");
    std::fs::write(&not_sqlite, format!("{SECRET} {NAME}")).unwrap();
    let broken = not_sqlite.to_str().unwrap();
    cases.push(("collect bad db", run(&["collect", "--db", broken], "")));
    cases.push(("clear bad option", run(&["clear-local-data", "--db"], "")));

    // import-csv: a valid export, a malformed one, an unreadable path, and
    // bad options, all carrying markers.
    let good = dir.path().join("good.csv");
    std::fs::write(
        &good,
        libreview_csv(&[
            &format!("FreeStyle,{SERIAL},10-15-2026 08:00 AM,0,{VALUE},,{NOTE}"),
            &format!("FreeStyle,{SERIAL},10-15-2026 08:05 AM,6,,,{NOTE}"),
            &format!("FreeStyle,{SERIAL},not a time,0,{VALUE},,{NOTE}"),
        ]),
    )
    .unwrap();
    let good = good.to_str().unwrap();
    cases.push((
        "import without a patient",
        run(&["import-csv", good, "--timezone", "UTC", "--db", db], ""),
    ));
    let malformed = dir.path().join("malformed.csv");
    std::fs::write(
        &malformed,
        format!("{NAME},{SERIAL}\r\n{NOTE},\"{SECRET}\r\n"),
    )
    .unwrap();
    cases.push((
        "import malformed",
        run(
            &[
                "import-csv",
                malformed.to_str().unwrap(),
                "--timezone",
                "UTC",
                "--dry-run",
            ],
            "",
        ),
    ));
    let ambiguous = dir.path().join("ambiguous.csv");
    std::fs::write(
        &ambiguous,
        libreview_csv(&[&format!(
            "FreeStyle,{SERIAL},11-05-2026 08:00 AM,0,{VALUE},,{NOTE}"
        )]),
    )
    .unwrap();
    cases.push((
        "import ambiguous dates",
        run(
            &[
                "import-csv",
                ambiguous.to_str().unwrap(),
                "--timezone",
                "UTC",
                "--dry-run",
            ],
            "",
        ),
    ));
    cases.push((
        "import bad zone",
        run(&["import-csv", good, "--timezone", SECRET], ""),
    ));

    for (label, output) in &cases {
        assert!(!output.status.success(), "{label} should fail");
        assert_clean(label, output);
    }
    // The dry run succeeds, reporting counts only.
    let dry = run(
        &[
            "import-csv",
            good,
            "--timezone",
            "UTC",
            "--dry-run",
            "--db",
            db,
        ],
        "",
    );
    assert!(dry.status.success());
    assert!(String::from_utf8_lossy(&dry.stdout).contains("would import: 1"));
    assert_clean("import dry run output", &dry);
}
